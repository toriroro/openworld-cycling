export interface GeneratedName {
  name: string;
  reading: string;
}

/** 2 音節の地名。除外表に当たったら引き直す */
export function placeName(seed: number, a: number, b: number, salt = 0): GeneratedName {
  for (let k = 0; k < 16; k++) {
    const h1 = hash(seed, a, b, salt * 131 + k * 2 + 1);
    const h2 = hash(seed, a, b, salt * 131 + k * 2 + 2);
    const head = HEAD[h1 % HEAD.length];
    const tail = TAIL[h2 % TAIL.length];
    const name = head[0] + tail[0];
    if (!NAME_EXCLUDE.has(name)) return { name, reading: head[1] + tail[1] };
  }
  return { name: "名無", reading: "ななし" };
}

const CAFE_PREFIX = ["喫茶", "珈琲", "カフェ", "喫茶室"];

export function cafeName(seed: number, a: number, b: number): string {
  const n = placeName(seed, a, b, 7);
  const p = CAFE_PREFIX[hash(seed, a, b, 77) % CAFE_PREFIX.length];
  return `${p} ${n.reading}`;
}

export function passName(seed: number, a: number, b: number): string {
  return placeName(seed, a, b, 11).name + "峠";
}

export function viewpointName(seed: number, a: number, b: number): string {
  return placeName(seed, a, b, 13).name + "展望地";
}
